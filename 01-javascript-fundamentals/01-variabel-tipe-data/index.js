//pembuatan variabel const
const nama = "Budi";
const umur = 17
const sudahMenikah = false;
const tinggiBadan = 170;
const hobi = "berenang";

console.log(nama);
console.log(umur);
console.log(sudahMenikah);
console.log(tinggiBadan);
console.log(hobi);

//menampilkan tipe data variabel const menggunakan typeof()
//untuk cek data apakah sesuai type nya string, number, boolean, dll
console.log(typeof (nama));
console.log(typeof (umur));
console.log(typeof (sudahMenikah));
console.log(typeof (tinggiBadan));
console.log(typeof (hobi));

//pembuatan variabel let menggunakan let (bisa diubah)
let kota = "Jakarta";

console.log(kota);

//mengubah nilai variabel let 
kota = "Bandung";

console.log(kota);

//pembuatan variabel let tanpa nilai
let alamat;
const nomorTelepon = null;

console.log(alamat);
console.log(typeof alamat);

console.log(nomorTelepon);
console.log(typeof nomorTelepon);